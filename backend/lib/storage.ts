// Media storage configuration, one place for every upload and media read (R2 through its S3 API).
//
// Fail closed:
// - every setting is required; nothing falls back to a hard-coded bucket or host;
// - outside production (SL_ENVIRONMENT !== 'production': staging, local, anything unset) a write bucket must be a
//   non-production bucket (sl-staging-* or sl-local-*) and no public URL may be a production media host, so staging
//   and local development can never write to, or publish links into, production media.
//
// Settings per purpose: MEDIA_<PURPOSE>_BUCKET and MEDIA_<PURPOSE>_PUBLIC_URL, plus the shared R2 credentials
// R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY. The home video is read-only: MEDIA_VIDEO_PUBLIC_URL.
// Keys are generated by the server from the owning record (never from a client filename).
import { S3Client } from '@aws-sdk/client-s3';

export type MediaPurpose = 'news' | 'players' | 'logos';
const PREFIX: Record<MediaPurpose, string> = { news: 'MEDIA_NEWS', players: 'MEDIA_PLAYERS', logos: 'MEDIA_LOGOS' };

// The production public media hosts that existed before the bucket reorganisation (read from the old code).
export const PRODUCTION_MEDIA_HOSTS = [
  'pub-faaac762b0254fb88c3967f021ced499.r2.dev', // team-logos
  'pub-156b66d0ff7841bc9601620610a8ebd3.r2.dev', // fresher-images (player portraits)
  'pub-b7d837d92cb644838cb24feef9b3329e.r2.dev', // intro video
];
const NON_PRODUCTION_BUCKET = /^sl-(staging|local)-[a-z0-9-]+$/;

export class StorageError extends Error {
  status = 503;
}

type Env = Record<string, string | undefined>;
const isProduction = (env: Env) => env.SL_ENVIRONMENT === 'production';

function publicBase(name: string, env: Env): string {
  const raw = env[name]?.trim();
  if (!raw) throw new StorageError(`Media storage is not configured: ${name} is not set.`);
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    throw new StorageError(`Media storage is not configured: ${name} is not a URL.`);
  }
  if (!isProduction(env) && PRODUCTION_MEDIA_HOSTS.includes(url.host)) {
    throw new StorageError(`Refusing production media host in ${name} outside production.`);
  }
  return raw.replace(/\/+$/, '');
}

export type Storage = { bucket: string; publicBase: string; client: () => S3Client; publicUrl: (key: string) => string };

export function storageFor(purpose: MediaPurpose, env: Env = process.env): Storage {
  const bucketName = `${PREFIX[purpose]}_BUCKET`;
  const bucket = env[bucketName]?.trim();
  if (!bucket) throw new StorageError(`Media storage is not configured: ${bucketName} is not set.`);
  if (!isProduction(env) && !NON_PRODUCTION_BUCKET.test(bucket)) {
    throw new StorageError(`Refusing bucket "${bucket}" outside production: only sl-staging-* or sl-local-* buckets may be written.`);
  }
  const base = publicBase(`${PREFIX[purpose]}_PUBLIC_URL`, env);
  const { R2_ACCOUNT_ID: account, R2_ACCESS_KEY_ID: accessKeyId, R2_SECRET_ACCESS_KEY: secretAccessKey } = env;
  if (!account || !accessKeyId || !secretAccessKey) {
    throw new StorageError('Media storage is not configured: the R2 credentials are not set.');
  }
  return {
    bucket,
    publicBase: base,
    client: () => new S3Client({ region: 'auto', endpoint: `https://${account}.r2.cloudflarestorage.com`, credentials: { accessKeyId, secretAccessKey } }),
    publicUrl: (key: string) => `${base}/${key.split('/').map(encodeURIComponent).join('/')}`,
  };
}

// Read-only media (the home video, proxied by /api/media). Any public host may be read, production included,
// because reading never changes it; the base must still be configured rather than hard-coded.
export function videoBase(env: Env = process.env): string {
  const raw = env.MEDIA_VIDEO_PUBLIC_URL?.trim();
  if (!raw) throw new StorageError('Media storage is not configured: MEDIA_VIDEO_PUBLIC_URL is not set.');
  return raw.replace(/\/+$/, '');
}

// Server-generated keys. Image types are fixed per purpose; a client filename never becomes part of a key.
export const IMAGE_EXTENSIONS: Record<string, string> = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/gif': 'gif' };
export const keys = {
  player: (playerId: string) => `players/${playerId}.png`,
  teamLogo: (teamId: string) => `teams/${teamId}/logo.png`,
  newsImage: (id: string, contentType: string) => {
    const ext = IMAGE_EXTENSIONS[contentType];
    if (!ext) throw Object.assign(new Error('News images must be PNG, JPEG, WebP or GIF.'), { status: 400 });
    return `news/${id}.${ext}`;
  },
};
